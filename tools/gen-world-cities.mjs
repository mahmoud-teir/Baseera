/**
 * Generates src/data/world.ts — every country (Arabic names) with its capital and largest cities,
 * for the manual location picker. Offline data, so the picker works without permission or network.
 *
 * Sources (pinned):
 *   world-countries@5.1.0          country codes and Arabic names (translations.ara.common)
 *   all-the-cities@3.1.0           GeoNames cities ≥1000 inhabitants: coordinates, population, PPLC = capital
 *   @photostructure/tz-lookup@11.7.0  IANA time zone for each city's coordinates
 *
 * Run (the packages are not app dependencies):
 *   npm i --prefix <dir> all-the-cities@3.1.0 world-countries@5.1.0 @photostructure/tz-lookup@11.7.0
 *   node tools/gen-world-cities.mjs <dir>/node_modules
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const PER_COUNTRY = 12;
const from = process.argv[2];
if (!from) throw new Error('usage: node tools/gen-world-cities.mjs <node_modules dir>');
const req = createRequire(path.resolve(from, 'x.js'));
const cities = req('all-the-cities');
const countries = req('world-countries');
const tzLookup = req('@photostructure/tz-lookup');

const byCc = new Map();
for (const c of cities) {
  if (!byCc.has(c.country)) byCc.set(c.country, []);
  byCc.get(c.country).push(c);
}

const tzs = [];
const tzIndex = (tz) => {
  let i = tzs.indexOf(tz);
  if (i < 0) i = tzs.push(tz) - 1;
  return i;
};

const outCountries = [];
const outCities = [];
for (const k of countries) {
  const list = byCc.get(k.cca2);
  if (!list?.length) continue;
  const name = k.translations?.ara?.common;
  if (!name) throw new Error('no Arabic name for ' + k.cca2);
  outCountries.push([k.cca2, name, k.name.common]);
  const caps = list.filter((c) => c.featureCode === 'PPLC');
  const rest = list.filter((c) => c.featureCode !== 'PPLC').sort((a, b) => b.population - a.population);
  const picked = [...caps, ...rest].slice(0, Math.max(PER_COUNTRY, caps.length));
  for (const c of picked) {
    const [lon, lat] = c.loc.coordinates;
    outCities.push([k.cca2, c.name, +lat.toFixed(4), +lon.toFixed(4), tzIndex(tzLookup(lat, lon)), c.featureCode === 'PPLC' ? 1 : 0]);
  }
}
outCountries.sort((a, b) => a[1].localeCompare(b[1], 'ar'));

const src = `// GENERATED by tools/gen-world-cities.mjs — do not edit by hand.
// Countries: world-countries@5.1.0 (Arabic names). Cities: GeoNames via all-the-cities@3.1.0 (capital +
// ${PER_COUNTRY} most populous per country). Time zones: @photostructure/tz-lookup@11.7.0.

/** [ISO code, Arabic name, English name], sorted by Arabic name. */
export const COUNTRY_ROWS: [string, string, string][] = ${JSON.stringify(outCountries)};

export const TZS: string[] = ${JSON.stringify(tzs)};

/** [ISO code, name, lat, lon, index into TZS, 1 = capital] */
export const CITY_ROWS: [string, string, number, number, number, 0 | 1][] = ${JSON.stringify(outCities)};
`;
writeFileSync(new URL('../src/data/world.ts', import.meta.url), src);
console.log(`${outCountries.length} countries, ${outCities.length} cities, ${tzs.length} zones, ${(src.length / 1024).toFixed(0)} KB`);
