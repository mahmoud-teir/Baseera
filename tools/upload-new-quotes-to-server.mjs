async function main() {
  const sb = createClient(url, anonKey);
  console.log(`Connecting to: ${url}`);
  console.log(`Authenticating as: ${email}`);

  const { data: auth, error: authErr } = await sb.auth.signInWithPassword({ email, password });
  if (authErr) {
    console.error('Sign in error:', authErr.message);
    process.exit(1);
  }

  console.log(`Authenticated successfully. Uploading and publishing ${NEW_QUOTES.length} quotes on the server...`);

  for (const q of NEW_QUOTES) {
    try {
      // 1. Save Draft
      const { data: id, error: draftErr } = await sb.rpc('admin_save_draft', {
        p_kind: 'quote',
        p_slot: q.slot,
        p_data: q.data,
      });

      if (draftErr) {
        console.warn(`Error drafting ${q.slot}:`, draftErr.message);
        continue;
      }

      // 2. Submit to review
      await sb.rpc('admin_transition', { p_kind: 'ct', p_id: id, p_action: 'send' });

      // 3. Approve and publish
      const { data: status, error: appErr } = await sb.rpc('admin_transition', {
        p_kind: 'ct',
        p_id: id,
        p_action: 'approve',
      });

      if (appErr) {
        console.warn(`Error approving ${q.slot}:`, appErr.message);
      } else {
        console.log(`✓ Published [${q.slot}] ${q.data.scholar}: «${q.data.text.slice(0, 35)}...» [status: ${status}]`);
      }
    } catch (err) {
      console.warn(`Exception for ${q.slot}:`, err.message);
    }
  }

  // Verify total published on server
  const { data: allPub } = await sb.from('published_content').select('slot').eq('kind', 'quote');
  console.log(`\n🎉 Total published quotes now live on Supabase server: ${allPub?.length || 0}`);
}

main().catch(console.error);
